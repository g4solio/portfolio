// Writes app/tokens.css from brand/tokens.json: the Paper theme as custom properties on :root.
// Run: node scripts/tokens.mjs (also runs before `next build`, see package.json)
import { readFile, writeFile } from "node:fs/promises";

const tokens = JSON.parse(await readFile("brand/tokens.json", "utf8"));
const resolve = (value, theme) => {
  const m = /^\{(.+)\}$/.exec(value);
  if (!m) return value;
  const target = tokens.color.find((t) => t.name === m[1]);
  if (!target) throw new Error(`alias to unknown token: ${value}`);
  return resolve(target[theme], theme);
};
const lines = tokens.color.map((t) => `  --${t.name}: ${resolve(t.paper, "paper")};`);
const css = `/* Generated by scripts/tokens.mjs from brand/tokens.json. Do not edit by hand. */\n:root {\n${lines.join("\n")}\n}\n`;
await writeFile("app/tokens.css", css);
console.log(`app/tokens.css written (${tokens.color.length} tokens)`);
