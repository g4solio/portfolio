// Generates components/wordmark.generated.ts: the hero wordmark as one SVG path per letter,
// from the static 600 instance of Space Grotesk, so the page can pencil and ink it.
// Run: node scripts/wordmark.mjs
import opentype from "opentype.js";
import { decompress } from "wawoff2";
import { readFile, writeFile } from "node:fs/promises";

const TEXT = "DAVIDE GOZZI";
const SIZE = 100; // viewBox units per em
const LETTER_SPACING = -0.015; // em, as the h1 sets it

const woff2 = await readFile("scripts/fonts/space-grotesk-latin-600-normal.woff2");
const ttf = Buffer.from(await decompress(woff2));
const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));

const paths = font
  .getPaths(TEXT, 0, 0, SIZE, { kerning: true, letterSpacing: LETTER_SPACING })
  .map((p) => ({ d: p.toPathData(2), box: p.getBoundingBox() }))
  .filter((p) => p.d.length > 0);

const x1 = Math.min(...paths.map((p) => p.box.x1));
const y1 = Math.min(...paths.map((p) => p.box.y1));
const x2 = Math.max(...paths.map((p) => p.box.x2));
const y2 = Math.max(...paths.map((p) => p.box.y2));
const pad = 2;
const viewBox = [x1 - pad, y1 - pad, x2 - x1 + pad * 2, y2 - y1 + pad * 2].map((n) => +n.toFixed(2));

const out = `// Generated by scripts/wordmark.mjs from Space Grotesk 600. Do not edit by hand.
export const wordmark = {
  text: ${JSON.stringify(TEXT)},
  viewBox: ${JSON.stringify(viewBox.join(" "))},
  /** height of the drawn box in em of the h1 font size */
  heightEm: ${(viewBox[3] / SIZE).toFixed(4)},
  paths: ${JSON.stringify(paths.map((p) => p.d))},
} as const;
`;
await writeFile("components/wordmark.generated.ts", out);
console.log(`components/wordmark.generated.ts written: ${paths.length} letters, viewBox ${viewBox.join(" ")}`);
